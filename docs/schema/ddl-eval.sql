CREATE TABLE IF NOT EXISTS EVAL_TAG (
    TAG_ID      BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键',
    TAG_NAME    VARCHAR(50)  NOT NULL COMMENT '标签名称',
    STATUS      TINYINT      NOT NULL DEFAULT 1 COMMENT '1=启用, 0=停用',
    CREATE_TIME DATETIME     DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    UPDATE_TIME DATETIME     DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (TAG_ID),
    UNIQUE KEY UK_TAG_NAME (TAG_NAME)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='评价标签字典表（无类型，被评价/评价角色由使用处承载）';

CREATE TABLE IF NOT EXISTS EVAL_USER_TAG (
    ID        BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键',
    USER_ID   VARCHAR(50) NOT NULL COMMENT '人员工号，关联 PT_USER.USER_ID',
    TAG_ID    BIGINT NOT NULL COMMENT '标签ID，关联 EVAL_TAG.TAG_ID',
    ROLE_TYPE TINYINT NOT NULL COMMENT '1=被评价角色, 2=评价角色',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_USER_TAG_ROLE (USER_ID, TAG_ID, ROLE_TYPE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='人员标签关联表';

CREATE TABLE IF NOT EXISTS EVAL_RULE (
    RULE_ID        BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键',
    RULE_NAME      VARCHAR(100) NOT NULL COMMENT '规则名称',
    BE_EVAL_TAG_ID BIGINT       NOT NULL COMMENT '被评价人标签ID',
    STATUS         TINYINT      NOT NULL DEFAULT 1 COMMENT '1=启用, 0=停用',
    CREATE_TIME    DATETIME     DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    UPDATE_TIME    DATETIME     DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (RULE_ID),
    UNIQUE KEY UK_BE_EVAL_TAG (BE_EVAL_TAG_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='评价关系规则主表';

CREATE TABLE IF NOT EXISTS EVAL_RULE_GROUP (
    GROUP_ID    BIGINT        NOT NULL AUTO_INCREMENT COMMENT '主键',
    RULE_ID     BIGINT        NOT NULL COMMENT '所属规则',
    GROUP_TYPE  TINYINT       NOT NULL COMMENT '1=按标签选人, 2=部门员工组',
    EVAL_TAG_ID BIGINT        DEFAULT NULL COMMENT 'type=1时的评价人标签ID',
    WEIGHT      DECIMAL(5,2)  NOT NULL COMMENT '权重百分比',
    SORT_ORDER  INT           NOT NULL DEFAULT 0 COMMENT '排序',
    PRIMARY KEY (GROUP_ID),
    INDEX IDX_RULE_ID (RULE_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='评价人组明细表';

CREATE TABLE IF NOT EXISTS EVAL_TASK (
    TASK_ID     BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键',
    TASK_NAME   VARCHAR(200) NOT NULL COMMENT '任务名称',
    START_TIME  DATETIME     NOT NULL COMMENT '开始时间',
    END_TIME    DATETIME     NOT NULL COMMENT '截止时间',
    STATUS      TINYINT      NOT NULL DEFAULT 0 COMMENT '0=进行中, 1=已结束',
    CREATE_BY   VARCHAR(50)  DEFAULT NULL COMMENT '创建人工号',
    CREATE_TIME DATETIME     DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    UPDATE_TIME DATETIME     DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (TASK_ID),
    INDEX IDX_STATUS_END (STATUS, END_TIME)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='评价任务表';

CREATE TABLE IF NOT EXISTS EVAL_TASK_TARGET (
    TARGET_ID        BIGINT        NOT NULL AUTO_INCREMENT COMMENT '主键',
    TASK_ID          BIGINT        NOT NULL COMMENT '所属任务',
    BE_EVAL_USER_ID  VARCHAR(50)   NOT NULL COMMENT '被评价人工号',
    RULE_ID          BIGINT        NOT NULL COMMENT '快照的规则ID',
    FINAL_SCORE      DECIMAL(5,1)  DEFAULT NULL COMMENT '最终得分',
    PRIMARY KEY (TARGET_ID),
    UNIQUE KEY UK_TASK_USER (TASK_ID, BE_EVAL_USER_ID),
    INDEX IDX_TASK_ID (TASK_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='任务被评价人明细';

CREATE TABLE IF NOT EXISTS EVAL_SCORE (
    SCORE_ID      BIGINT    NOT NULL AUTO_INCREMENT COMMENT '主键',
    TASK_ID       BIGINT    NOT NULL COMMENT '任务ID',
    TARGET_ID     BIGINT    NOT NULL COMMENT '关联 EVAL_TASK_TARGET',
    EVAL_USER_ID  VARCHAR(50) NOT NULL COMMENT '评价人工号',
    GROUP_ID      BIGINT    NOT NULL COMMENT '所属评价人组',
    SCORE         INT       NOT NULL COMMENT '打分 10~100',
    SUBMIT_TIME   DATETIME  NOT NULL COMMENT '提交时间',
    PRIMARY KEY (SCORE_ID),
    UNIQUE KEY UK_TARGET_EVALUATOR (TARGET_ID, EVAL_USER_ID),
    INDEX IDX_TASK_ID (TASK_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='评价打分记录';

CREATE TABLE IF NOT EXISTS EVAL_USER_SETTING (
    USER_ID       VARCHAR(50) NOT NULL COMMENT '工号，关联 PT_USER.USER_ID',
    EVAL_ENABLED  TINYINT     NOT NULL DEFAULT 0 COMMENT '是否启用评价：1=是 0=否',
    CREATED_TIME  DATETIME    DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    UPDATED_TIME  DATETIME    DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '最近更新时间',
    PRIMARY KEY (USER_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='人员评价设置（是否启用评价）';

-- =============================================================
-- 待处理任务（导入式评价任务）2026-06-10 新增
-- 显式配对模型：打分人×被打分人；与上方规则驱动 EVAL_TASK 体系并存
-- =============================================================

CREATE TABLE IF NOT EXISTS EVAL_ASSIGN_BATCH (
    BATCH_ID    BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键',
    BATCH_NAME  VARCHAR(200) DEFAULT NULL COMMENT '批次名称（可空）',
    TASK_TYPE   VARCHAR(50)  NOT NULL COMMENT '待处理任务类型 dict EVAL_IMPORT_TYPE: EVAL/REWARD',
    SOURCE      VARCHAR(50)  NOT NULL DEFAULT 'IMPORT' COMMENT '来源 dict EVAL_PENDING_SOURCE: IMPORT/AUTO',
    DEADLINE    DATETIME     NOT NULL COMMENT '打分截止时间',
    STATUS      TINYINT      NOT NULL DEFAULT 0 COMMENT '0=进行中, 1=已结束',
    CREATE_BY   VARCHAR(50)  DEFAULT NULL COMMENT '创建人工号',
    CREATE_TIME DATETIME     DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    PRIMARY KEY (BATCH_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='待处理任务批次（一次导入=一批）';

CREATE TABLE IF NOT EXISTS EVAL_ASSIGN_ITEM (
    ITEM_ID           BIGINT      NOT NULL AUTO_INCREMENT COMMENT '主键',
    BATCH_ID          BIGINT      NOT NULL COMMENT '所属批次',
    EVAL_USER_ID      VARCHAR(50) NOT NULL COMMENT '打分人工号',
    EVAL_USER_NAME    VARCHAR(100) DEFAULT NULL COMMENT '打分人姓名（导入快照）',
    EVAL_USER_TAG     VARCHAR(100) DEFAULT NULL COMMENT '打分人标签（导入快照）',
    EVAL_USER_DEPT    VARCHAR(200) DEFAULT NULL COMMENT '打分人部门（导入快照）',
    BE_EVAL_USER_ID   VARCHAR(50) NOT NULL COMMENT '被打分人工号',
    BE_EVAL_USER_NAME VARCHAR(100) DEFAULT NULL COMMENT '被打分人姓名（导入快照）',
    BE_EVAL_DEPT      VARCHAR(200) NOT NULL DEFAULT '' COMMENT '被打分人部门（导入快照，分组键，空存空串）',
    GROUP_DEPT        VARCHAR(200) NOT NULL DEFAULT '' COMMENT '分组部门（导入快照，汇总优先键，空串则回退 be_eval_dept）',
    BE_EVAL_TAG       VARCHAR(100) DEFAULT NULL COMMENT '被打分人标签（导入快照）',
    WEIGHT_TAG        VARCHAR(100) DEFAULT NULL COMMENT '权重标签 dict EVAL_WEIGHT_TAG',
    SCORE_TYPE        VARCHAR(50) NOT NULL COMMENT '评价类型 dict EVAL_SCORE_TYPE: NUM/GRADE',
    SCORE             INT         DEFAULT NULL COMMENT '打分（提交后填入）',
    SUBMITTED         TINYINT     NOT NULL DEFAULT 0 COMMENT '0=未提交, 1=已提交',
    SUBMIT_TIME       DATETIME    DEFAULT NULL COMMENT '提交时间',
    PRIMARY KEY (ITEM_ID),
    UNIQUE KEY UK_BATCH_PAIR (BATCH_ID, EVAL_USER_ID, BE_EVAL_USER_ID),
    INDEX IDX_SCORER (EVAL_USER_ID, SUBMITTED),
    INDEX IDX_BATCH (BATCH_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='待处理任务明细（打分人×被打分人 显式配对）';

-- =============================================================
-- 奖励分配明细表 EVAL_REWARD_ITEM（2026-07-11）
-- 批次复用 EVAL_ASSIGN_BATCH（TASK_TYPE=REWARD）；本表仅存奖励分配明细。
-- =============================================================
CREATE TABLE IF NOT EXISTS EVAL_REWARD_ITEM (
    ITEM_ID               BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键',
    BATCH_ID              BIGINT       NOT NULL COMMENT '所属批次(EVAL_ASSIGN_BATCH)',
    ASSIGN_USER_ID        VARCHAR(64)  NOT NULL COMMENT '分配人USER_ID(归一化后)',
    BE_ASSIGNED_USER_ID   VARCHAR(64)  NOT NULL COMMENT '被分配人工号(原样快照,不校验)',
    BE_ASSIGNED_USER_NAME VARCHAR(128) DEFAULT NULL COMMENT '被分配人姓名(快照)',
    DEPT_NAME             VARCHAR(128) NOT NULL DEFAULT '' COMMENT '部门名称(分组键)',
    ORIGINAL_VALUE        DECIMAL(18,4) DEFAULT NULL COMMENT '原始值(展示)',
    CASH_VALUE            DECIMAL(18,4) DEFAULT NULL COMMENT '兑现值(展示)',
    ASSIGN_TOTAL          DECIMAL(18,4) NOT NULL COMMENT '分配合计(组内一致,分配目标池)',
    ASSIGN_VALUE          DECIMAL(18,4) DEFAULT NULL COMMENT '分配值(提交时填入)',
    SUBMITTED             TINYINT      NOT NULL DEFAULT 0 COMMENT '0=未提交, 1=已提交',
    SUBMIT_TIME           DATETIME     DEFAULT NULL COMMENT '提交时间',
    CREATE_TIME           DATETIME     DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    PRIMARY KEY (ITEM_ID),
    INDEX IDX_REWARD_ASSIGNER (ASSIGN_USER_ID, BATCH_ID, DEPT_NAME, SUBMITTED),
    INDEX IDX_REWARD_BATCH (BATCH_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='奖励分配明细';
