-- -------------------------------------------
-- 2. 指标定义表
-- -------------------------------------------
CREATE TABLE IF NOT EXISTS `PERF_METRIC_DEF` (
  `id` varchar(32) NOT NULL COMMENT '指标ID',
  `metric_code` varchar(64) NOT NULL COMMENT '指标编码(唯一)',
  `metric_name` varchar(200) NOT NULL COMMENT '指标名称',
  `metric_name_en` varchar(200) DEFAULT NULL COMMENT '英文名',
  `metric_desc` text COMMENT '指标说明',
  `base_dim` varchar(20) DEFAULT NULL COMMENT '基础维度：EMP/ORG/CUST；NULL=维度无关型指标（V1.9 改造，2026-05-17）',
  `metric_level` int(11) NOT NULL COMMENT '指标层级：1/2/3',
  `calc_freq` varchar(20) NOT NULL COMMENT '计算频率：DAY/MONTH/QUARTER/YEAR',
  `calc_mode` varchar(20) NOT NULL COMMENT '计算方式：AUTO/MANUAL',
  `calc_logic_type` varchar(50) DEFAULT NULL COMMENT '逻辑类型：SQL/PROC/EXPR/SUMMARY',
  `sql_text` longtext COMMENT '一级指标SQL/存储过程文本',
  `expr_text` text COMMENT '二/三级指标表达式',
  `summary_rule` varchar(20) DEFAULT NULL COMMENT '机构汇总规则：SUM/AVG等',
  `ref_metric_codes` text COMMENT '引用指标列表(JSON数组)',
  `val_slot` int(11) DEFAULT NULL COMMENT '宽表槽位(1..200)',
  `unit` varchar(16) DEFAULT NULL COMMENT '单位：元/万元/%',
  `decimal_places` tinyint DEFAULT '2' COMMENT '小数位数',
  `deleted` tinyint DEFAULT '0' COMMENT '0=存在 1=删除',
  `description` varchar(500) DEFAULT NULL COMMENT '指标详细描述（补充 metric_desc）',
  `metric_category` varchar(50) DEFAULT NULL COMMENT 'V1.9 指标分类（规模类/效益类/质量类/合规类等）',
  `status` varchar(20) NOT NULL DEFAULT 'ACTIVE' COMMENT '状态：ACTIVE/DISABLED',
  `created_by` varchar(32) DEFAULT NULL COMMENT '创建人',
  `created_time` datetime DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `updated_by` varchar(32) DEFAULT NULL COMMENT '更新人',
  `updated_time` datetime DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  -- V1.7 新增（指标级 Quartz 调度改造，2026-04-30）
  `cron_expr` varchar(120) DEFAULT NULL COMMENT 'V1.7 自定义 cron；留空按 calc_freq 推导默认',
  `subject_sql` longtext COMMENT 'V1.7 EXPR/GROOVY 类型主体集合 SQL（SQL/PROC/SUMMARY 不需要）',
  `last_run_time` datetime DEFAULT NULL COMMENT 'V1.7 最近一次自动调度执行时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_metric_code` (`metric_code`),
  UNIQUE KEY `uk_metric_name_alive` ((IF(deleted=0, metric_name, NULL))), -- V1.11 指标中文名按未软删除唯一
  UNIQUE KEY `uk_base_dim_slot_alive` ((IF(deleted=0, CONCAT(base_dim,'#',val_slot), NULL))),
  KEY `idx_dim_level` (`base_dim`, `metric_level`),
  KEY `idx_status` (`status`),
  KEY `idx_val_slot` (`val_slot`),
  KEY `idx_metric_def_schedulable` (`status`, `calc_mode`, `deleted`), -- V1.7 启动同步 + HealthCheck 扫描
  KEY `idx_metric_category` (`metric_category`) -- V1.9 指标分类筛选
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='指标定义表';

