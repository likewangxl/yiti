-- =============================================================================
-- 2026-06-03 公告管理（查看全部 + 新增/置顶/取消置顶/删除/附件上传）仅系统管理员(SYS_ADMIN)
-- -----------------------------------------------------------------------------
-- 需求：
--   1) 公告 新增/置顶/取消置顶/删除/附件上传 仅 SYS_ADMIN 可操作；
--   2) 只有 SYS_ADMIN 能看「所有公告」（管理端列表含已删除），其他人只看「已发布」公告
--      （走门户端 /api/portal/announcements，service 已按 is_deleted=0 过滤，无需改）。
-- 做法：把公告管理相关 PT_RESOURCE（操作 + 管理端列表 + 公告管理菜单）收紧为仅 R_ADMIN。
--   - SYS_ADMIN(R_ADMIN) 走拦截器 systemAdmin 旁路，无需显式授权即可访问；这里保留 R_ADMIN 行语义清晰。
--   - 其他人通过工作台/门户（仅已发布、非删除）查看公告，detail 的置顶/删除按钮前端按 isSystemAdmin 隐藏。
-- 执行：yiti(dev) + onepl(prod) 双库（已于 2026-06-03 应用）。
-- =============================================================================

DELETE FROM PT_ROLE_RESOURCE
WHERE RESOURCE_ID IN (
        'RES_ANN_CREATE',     -- 新增公告
        'RES_ANN_DELETE',     -- 删除公告
        'RES_ANN_PIN',        -- 置顶/取消置顶
        'RES_ANN_UPLOAD',     -- 公告附件上传
        'RES_ANN_ADMIN_LIST', -- 管理端列表（含已删除=看全部）
        'M_SYS_ANN'           -- 「公告管理」菜单
      )
  AND ROLE_ID <> 'R_ADMIN';
