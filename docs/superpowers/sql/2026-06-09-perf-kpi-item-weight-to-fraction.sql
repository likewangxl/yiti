-- ============================================================================
-- PERF_KPI_ITEM.weight 口径统一为「小数占比」（sum=1），前端按百分比展示（读取 ×100 / 入库 ÷100）。
-- 历史数据中部分库（如 onepl）以「整百分比」存储（如 40 / 60），需一次性 ÷100 归一为小数。
-- 判别：小数占比恒 <= 1，整百分比 > 1 —— 用 weight > 1 作为安全判别，幂等（再次执行 0.4 不 >1 跳过）。
-- yiti（已是小数 <=1，无行命中，no-op） + onepl（40/60 → 0.4/0.6）双库执行。
-- ============================================================================

UPDATE yiti.PERF_KPI_ITEM  SET weight = weight / 100 WHERE weight > 1;
UPDATE onepl.PERF_KPI_ITEM SET weight = weight / 100 WHERE weight > 1;
