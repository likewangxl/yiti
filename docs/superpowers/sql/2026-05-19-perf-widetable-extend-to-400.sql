-- 背景：
--   配合 PERF_METRIC_DEF.val_slot 新分段（L1=[1,200] / L2=[201,300] / L3=[301,400]），
--   将 EMP_INDEX_RESULT / ORG_INDEX_RESULT / CUST_INDEX_RESULT 三张宽表
--   原本 val_1..val_200 扩展到 val_1..val_400，新增 200 列 × 3 表 = 600 列。
--
-- 影响：
--   - InnoDB 行长：现有 200 列 × decimal(20,4) ≈ 1800 字节，加键约 2000 字节，
--     扩到 400 列 ≈ 3800 字节，远低于 ROW_FORMAT=DYNAMIC 行长上限（8126B），安全
--   - ALTER TABLE 一次性 200 ADD COLUMN，MySQL 8.0 走 INPLACE 算法，不重建数据页
--   - 在线 DDL：ADD COLUMN ... DEFAULT NULL 是 INSTANT 算法（MySQL 8.0+），
--     秒级完成，不锁业务
--
-- 备份：执行前 mysqldump 备份（结构，不要数据，三表数据量可能巨大）
--   mysqldump -h localhost -u root -p<pwd> --no-data onepl \
--     EMP_INDEX_RESULT ORG_INDEX_RESULT CUST_INDEX_RESULT \
--     > docs/superpowers/sql/backup/2026-05-19-perf-widetable-extend-to-400-schema.sql
--
-- 配套 Java 改动（同 PR 一起上线）：
--   - SlotMapTypeHandler.MAX_SLOT 200 → 400
--   - MetricCalcService.validateSlot 上限 [1,200] → [1,400]
--   - KpiCalcService.java:115 slot 校验上限 → 400
--   - MetricSlotService.rangeOf L1/L2/L3 重切
--   - 3 个 *IndexResultMapper.xml 注释 [1,200] → [1,400]
--
-- 幂等：再次执行直接报 "Duplicate column name val_201"，MySQL 不允许重复列名
--      → 上线时确认是新环境再跑，已跑过的环境跳过本文件
-- =============================================================================

