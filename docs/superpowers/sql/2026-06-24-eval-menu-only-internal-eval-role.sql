-- 2026-06-24 内部评价菜单授权收口：
-- 管理类菜单(标签管理/人员标签/评价规则/评价任务)仅「内部评价」角色(ROLE_ID=240)可见；
-- 其余角色只保留「我的评价」(M_EVAL_MY_TASKS)。纯菜单授权调整，不改代码。

-- 1) 从非 240 角色收回 4 个管理类 eval 菜单
DELETE FROM PT_ROLE_RESOURCE
 WHERE RESOURCE_ID IN ('M_EVAL_TAGS','M_EVAL_USER_TAGS','M_EVAL_RULES','M_EVAL_TASKS')
   AND ROLE_ID <> 240;

-- 2) 给内部评价角色(240) 补齐全部 eval 菜单（先删后插，幂等）
DELETE FROM PT_ROLE_RESOURCE
 WHERE ROLE_ID = 240
   AND RESOURCE_ID IN ('M_GROUP_EVAL','M_EVAL_TAGS','M_EVAL_USER_TAGS','M_EVAL_RULES','M_EVAL_TASKS','M_EVAL_MY_TASKS');
INSERT INTO PT_ROLE_RESOURCE (ID, ROLE_ID, RESOURCE_ID, SYS_CODE, CREATE_TIME)
SELECT UPPER(SUBSTRING(REPLACE(UUID(),'-',''),1,16)), 240, r.RID, 'PLATFORM', NOW()
FROM (SELECT 'M_GROUP_EVAL' RID UNION ALL SELECT 'M_EVAL_TAGS' UNION ALL SELECT 'M_EVAL_USER_TAGS'
      UNION ALL SELECT 'M_EVAL_RULES' UNION ALL SELECT 'M_EVAL_TASKS' UNION ALL SELECT 'M_EVAL_MY_TASKS') r;
