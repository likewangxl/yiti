-- 大屏指标目录资源登记。
-- 仅包含事务、INSERT、UPDATE。执行前必须先对获准的隔离库做只读盘点，并取得明确确认。
-- 本文件不代表已经在目标库执行。

START TRANSACTION;

INSERT INTO PT_RESOURCE
    (RESOURCE_ID, RESOURCE_URL, RESOURCE_METHOD, MENU_NAME, MENU_ICON_URL,
     MENU_RANK_NO, ISMENU, MENU_ENDFLAG, PARENT_RESOURCE_ID, STATUS, SYS_CODE,
     CREATE_USER, REMARK)
SELECT 'R_RPT_SCR_METRIC_CAT', '/api/screen/admin/metric-catalog', 'GET', '大屏-指标目录', NULL,
       0, 0, '0', NULL, 0, 'RPT',
       'screen-metric-catalog', '大屏绑定读取 PERF_METRIC_DEF 只读目录'
FROM DUAL
WHERE NOT EXISTS (
    SELECT 1 FROM PT_RESOURCE existing WHERE existing.RESOURCE_ID = 'R_RPT_SCR_METRIC_CAT'
);

UPDATE PT_RESOURCE
SET RESOURCE_URL = '/api/screen/admin/metric-catalog',
    RESOURCE_METHOD = 'GET',
    MENU_NAME = '大屏-指标目录',
    STATUS = 0,
    SYS_CODE = 'RPT',
    REMARK = '大屏绑定读取 PERF_METRIC_DEF 只读目录'
WHERE RESOURCE_ID = 'R_RPT_SCR_METRIC_CAT';

INSERT INTO PT_ROLE_RESOURCE (ID, ROLE_ID, RESOURCE_ID, SYS_CODE)
SELECT MD5(CONCAT(rr.ROLE_ID, '#R_RPT_SCR_METRIC_CAT')), rr.ROLE_ID, 'R_RPT_SCR_METRIC_CAT', rr.SYS_CODE
FROM PT_ROLE_RESOURCE rr
WHERE rr.RESOURCE_ID = 'R_RPT_SCR_DS_LIST'
  AND NOT EXISTS (
      SELECT 1 FROM PT_ROLE_RESOURCE existing
      WHERE existing.ROLE_ID = rr.ROLE_ID AND existing.RESOURCE_ID = 'R_RPT_SCR_METRIC_CAT'
  );

INSERT INTO PT_ROLE_RESOURCE (ID, ROLE_ID, RESOURCE_ID, SYS_CODE)
SELECT MD5(CONCAT('1', '#R_RPT_SCR_METRIC_CAT')), '1', 'R_RPT_SCR_METRIC_CAT', 'PLATFORM'
FROM DUAL
WHERE NOT EXISTS (
    SELECT 1 FROM PT_ROLE_RESOURCE existing
    WHERE existing.ROLE_ID = '1' AND existing.RESOURCE_ID = 'R_RPT_SCR_METRIC_CAT'
);

COMMIT;
