SET PARENT_RESOURCE_ID = 'M_MKT_TOUCH_OV',
    UPDATE_USER = 'customer-menu-dedupe-0811',
    REMARK = '触达任务一览'
WHERE RESOURCE_ID = 'C_TOUCH_LOG_LIST';

