DELETE FROM PT_RESOURCE WHERE RESOURCE_ID = 'M_MKT_TOUCH_LOG';

UPDATE PT_RESOURCE
SET RESOURCE_URL = '/touches/overview',
    MENU_NAME = '触达任务一览',
    UPDATE_USER = 'customer-menu-dedupe-0811',
    REMARK = '触达任务管理视图'
WHERE RESOURCE_ID = 'M_MKT_TOUCH_OV';

