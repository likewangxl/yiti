SELECT REPLACE(UUID(), '-', ''), CONCAT('ui.login-screen.role.', r.ROLE_ID),
  JSON_OBJECT('target', CASE
    WHEN r.ROLE_CODE IN ('R_RM','CUST_MARKETING_MANAGER') THEN 'PERSONAL'
    WHEN r.ROLE_CODE = 'BRANCH_HEAD' THEN 'BRANCH'
    WHEN r.ROLE_CODE = 'BRANCH_PRE' THEN 'PROVINCE'
    WHEN r.ROLE_CODE IN ('RETAIL_DEPT','RETAIL_DEPT_LEADER') THEN 'RETAIL'
    WHEN r.ROLE_CODE IN ('CORP_DEPT','CORP_DEPT_LEADER') THEN 'CORPORATE'
