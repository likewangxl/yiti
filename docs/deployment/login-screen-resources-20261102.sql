FROM PT_ROLE r
WHERE r.RECORD_STATUS = 0
  AND r.ROLE_CODE IN ('R_RM','CUST_MARKETING_MANAGER','BRANCH_HEAD','BRANCH_PRE','RETAIL_DEPT','RETAIL_DEPT_LEADER','CORP_DEPT','CORP_DEPT_LEADER')
  AND NOT EXISTS (SELECT 1 FROM SYS_CONFIG_KV c WHERE c.config_key = CONCAT('ui.login-screen.role.', r.ROLE_ID));

