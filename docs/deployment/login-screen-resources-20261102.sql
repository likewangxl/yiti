INSERT INTO PT_ROLE_RESOURCE (ID, ROLE_ID, RESOURCE_ID, SYS_CODE, CREATE_TIME)
SELECT REPLACE(UUID(), '-', ''), r.ROLE_ID, p.RESOURCE_ID, 'GOV', CURRENT_TIMESTAMP
FROM PT_ROLE r JOIN PT_RESOURCE p ON p.RESOURCE_ID IN ('G_LOGIN_SCREEN_GET', 'G_LOGIN_SCREEN_PUT', 'G_LOGIN_SCREEN_SELF')
WHERE r.RECORD_STATUS = 0 AND p.STATUS = 0
  AND (p.RESOURCE_ID = 'G_LOGIN_SCREEN_SELF' OR r.ROLE_CODE = 'SYS_ADMIN')
  AND NOT EXISTS (SELECT 1 FROM PT_ROLE_RESOURCE rr WHERE rr.ROLE_ID = r.ROLE_ID AND rr.RESOURCE_ID = p.RESOURCE_ID);

